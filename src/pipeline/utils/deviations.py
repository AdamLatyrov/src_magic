"""Поля общего отклонения: что умеют разбирать все проверяющие ветки.

Форма отклонения одна на ветки (`pipeline.schemas.nodes.CXDeviation`), поэтому и
разбор общих полей — текста поля, номера экрана, перечня дословных цитат и
координаты пина — у них общий: держать его дважды значило бы однажды развести
правила, после чего сравнить прогоны блоков и проверок пути стало бы нельзя.

Политики при этом остаются в своих ветках: какой код дефекта законен и какую зону
ему ставить, решает справочник (`pipeline.utils.block_findings`), а в ветке проблем
пути адрес находке вообще даёт разметчик
(`pipeline.agent.journey_frictions.nodes.map_journey_frictions`). Здесь только
приведение значения, которое написала модель, к полю схемы.
"""

from src.pipeline.settings.params.nodes import PCT_VALUE


def step_of(raw: object) -> int:
    """Номер экрана; модельное «7», 7, «кадр 7» и пустота сводятся к одному.

    Номер берут из подписи кадра, и модель подписывает его по-своему: цифра в
    строке с текстом встречается чаще, чем честное число. Ноль значит «экран не
    назван» — то же значение, что у пропущенного поля.

    :param raw: значение поля `step` или `related_step` из ответа модели
    :return: номер экрана 1-based либо 0
    """
    digits = "".join(char for char in str(raw or "") if char.isdigit())
    return int(digits) if digits else 0


def text_of(raw: object) -> str:
    """Текст поля ответа: написанная моделью пустота остаётся пустой строкой.

    Модель пишет `"text": null` там, где схема ждёт строку, и ключ при этом
    присутствует — `item.get("text", "")` возвращает `None`, а `str(None)` даёт
    слово `None`, которое потом читается в отчёте как пояснение находки. Пустая
    строка значит ровно то же «пояснения нет», что и отсутствующее поле.

    :param raw: текстовое поле ответа модели
    :return: текст поля либо пустая строка
    """
    return "" if raw is None else str(raw)


def quotes_of(raw: object) -> list[str]:
    """Дословные цитаты: перечень непустых строк вместо того, что написали.

    Цитата — единственное, что доказывает чёрную зону, поэтому её отсутствие или
    пустая строка значат «улики нет», а не «улика есть, но пустая». Одиночная
    строка вместо списка — обычный ответ контура на вопрос про перечень.

    :param raw: значение поля `evidence` из ответа модели
    :return: цитаты без пустых строк
    """
    if isinstance(raw, str):
        raw = [raw]
    return [str(line).strip() for line in raw or [] if str(line).strip()]


def pct_of(raw: object, center: float) -> float:
    """Координата пина в процентах 0..100; центр — если указать место нечем.

    Модель пишет процент то числом, то строкой со знаком процента, а слову
    промпта «поставь 0, если место указать нечем» показывать находку в углу
    экрана хуже, чем посередине: ноль и всё, что не разобралось, становится
    центром.

    Дробная часть читается вместе с разделителем: вычеркнутая точка оставляла от
    `12.0` сто двадцать процентов, и исправная координата молча уезжала за край
    кадра — ровно то же значение, что у совсем нечитаемого.

    :param raw: `x` или `y` из ответа модели
    :param center: координата центра кадра
        (`pipeline.settings.params.nodes.PIN_CENTER`)
    :return: проценты от 0 до 100
    """
    found = PCT_VALUE.search(str(raw or ""))
    if found is None:
        return center
    try:
        value = float(found.group(0).replace(",", "."))
    except ValueError:
        return center
    if not 0 < value <= 100:
        return center
    return value
