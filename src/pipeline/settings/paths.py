"""Путь настройки: от какого каталога пайплайн читает названные в настройках файлы.

В настройках файлы названы относительными путями — `prompts_dir`, `criteria_model`,
файл конфига графа. Резолвить их надо от корня сервиса, а не от рабочего каталога
процесса: точка входа поднимается из `/app`, лаборатория — из своего каталога,
сервисный менеджер — откуда его вызвали. От рабочего каталога путь зависел так, что
один и тот же конфиг находил справочник в одном случае и терял в другом, а потеря
выглядела как «настроек нет», потому что молча прочитать чужой файл того же имени
тоже успех.

Корень выводится из положения пакета, а не из переменной окружения: образ кладёт
дерево вместе с `configs/` и `prompts/` рядом с ним, и сместить справочник стенд
вправе абсолютным путём настройки — такой путь остаётся абсолютным.

Правило живёт здесь, а не в интеграции: пути читают настройки этапов и сами узлы
пайплайна, и обращаться за ними наружу значило бы, что прогон не работает без
окружающего сервиса.
"""

from pathlib import Path


def service_root() -> Path:
    """Каталог, относительно которого записаны пути в файле настроек."""
    return Path(__file__).resolve().parents[3]


def service_path(relative: str) -> Path:
    """Настроенческий путь в путь на диске; абсолютное значение — как названо.

    :param relative: путь из настройки — от корня сервиса или абсолютный
    :return: путь, по которому файл читается
    """
    return service_root().joinpath(relative)
