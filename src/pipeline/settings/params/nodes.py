#: величина, по которой сверяют путь: разряды через пробел, сумма с валютой,
#: процент. Перевод строки разделителем разрядов не считается — иначе последние
#: цифры счёта склеиваются со суммой следующей строки в одну выдуманную величину.
#: Перед числом не должно быть ни цифры, ни разделителя: «•••4835 108,59 ₽» —
#: это последние четыре цифры счёта и сумма, а не одно число в 835 тысяч.
#: Одинокого числа («2026», дата «13.09.21») здесь нет: последней цифрой карты
#: сверять нечего, а от дат перечень начал бы разрастаться
VALUE_FOUND = re.compile(
    r"(?<![\d.,])\d{1,3}(?:[ \u00a0]\d{3})+(?:[.,]\d{1,2})?"
    r"(?: *(?:₽|руб\w*|евро|RUB|EUR|USD))?"
    r"|(?<![\d.,])\d+(?:[.,]\d+)? *(?:%|₽|руб\w*|процент\w*|евро|RUB|EUR|USD)"
)
#: итог одной меры в разборе проблем пути: найдено, норма, к пути не применима.
#: Контур пишет итог своими словами («нарушение», «кандидат», «всё хорошо»), и
#: разбор сводит их к этим трём — только так ноль находок различает «меру сняли»
#: и «меру не смотрели»
UNIT_FINDING = "finding"
UNIT_NORM = "norm"
UNIT_NA = "not_applicable"
#: как контур называет каждый итог меры — сводка по подстроке, в этом порядке
UNIT_WORDS = {
    UNIT_NA: (UNIT_NA, "not applic", "н/п", "не применим", "неприменим"),
    UNIT_FINDING: (UNIT_FINDING, "нарушен", "кандидат", "находк", "problem"),
    UNIT_NORM: (
        UNIT_NORM,
        "норм",
        "чисто",
        "соответству",
        "хорош",
        "ok",
    ),
}
#: координата пина по умолчанию: центр кадра. `0` модель ставит по слову промпта
#: «место указать нечем», и показывать такую находку в углу экрана хуже, чем
#: посередине: пин тут только подписывает место на экране, а не указывает точку
PIN_CENTER = 50.0
#: первое число строки вместе с дробной частью: процент бывает и числом (`30`), и
#: строкой («30 %», «62,5»)
PCT_VALUE = re.compile(r"-?\d+(?:[.,]\d+)?")


