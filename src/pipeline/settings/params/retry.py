"""Сколько раз и с какими паузами переспрашивается то, что уже спрашивали.

Отдельный модуль, а не `nodes.py`: здесь щедрость к контуру, а не правила
оценки пути. Значения меряются секундными и минутными паузами нарочно — очередь
обращений к контуру считается по числу запросов за промежуток времени, поэтому
секунды её не рассасывают.
"""

#: Сколько раз спрашивать одно обращение к контуру, когда сбой лечится повтором.
ASK_ATTEMPTS = 3

#: Пауза перед повтором, растущая с попыткой (15 с, затем 30 с). Очередь контура
#: (429) считается по числу обращений клиента за промежуток времени, поэтому
#: секунды её не рассасывают: в прогоне 047 с паузой в три секунды повтор приходил
#: в ту же очередь и окно всё равно оставалось неотвеченным.
ASK_RETRY_PAUSE_S = 15.0

#: Пауза перед повтором после неразобранного ответа: щедрость генерации очередью
#: контура не является, и ждать минуту, чтобы спросить то же самое, незачем.
SHAPE_RETRY_PAUSE_S = 1.0

#: Сколько раз батч спрашивается одним вопросом, если ответ не разобрался либо
#: контур отказал временно. Повтор стоит того, что стоит одно обращение:
#: обрезанный на середине JSON — щедрость генерации, а не «в этой части пути
#: проблем нет», и без повтора батч молча списывался в `batches_broken`, унося
#: вердикты половины пути.
BATCH_ATTEMPTS = 3

#: Пауза перед местным повтором, растущая с попыткой (15 с, затем 30 с). Мерят её
#: минутами, а не секундами: очередь контура (429) считается по числу обращений
#: клиента за промежуток времени. Политикой графа этот случай не прикрыт: узел
#: перевызывает себя целиком только когда не отвечен ВЕСЬ блок.
BATCH_RETRY_PAUSE_S = 15.0
