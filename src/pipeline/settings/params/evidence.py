"""Чем улика сверяется с текстом кадра.

Регулярки разбора цитаты живут отдельно от `pipeline.utils.evidence`, потому что
строгий разбор — это настройка: слабое сравнение молча пропускает выдуманную
цитату, а по ней ветка держит чёрную зону.
"""

import re

#: номер кадра в начале строки улики («кадр 12: „…"») — им улика и привязывается
QUOTE_SCREEN = re.compile(r"^\D*(\d+)")
#: сама надпись внутри кавычек: контур тонит их по-своему («», "", „")
QUOTED = re.compile(
    "[«\"„'`](.+?)[»\"”'']",
    re.DOTALL,
)
#: всё, что не буква и не цифра: оформлением два текста одного экрана различаются,
#: содержанием — нет
NOT_WORD = re.compile(r"[^0-9a-zа-яё]+")
#: ряды цифр в уже сглаженном тексте: «25 000» и «25000» дают один ряд, а «410» и
#: «4100» — разные, и цитата с числом обязана попадать в ряд целиком
NUMBER_RUNS = re.compile(r"\d+")
#: пропуск внутри цитаты («кнопка … Продолжить»): каждый осколок обязан читаться
OMISSION = re.compile(r"\.\.\.|…")
