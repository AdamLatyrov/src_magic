"""Почему выгрузка не стала справочником.

Одна ошибка сборки и перечень причин в её текст. Отдавать первую причину
означало бы чинить файл по одному сообщению за прогон, поэтому причин в текст
ходит несколько, а порядок их нарочный.
"""


class CatalogValidationError(ValueError):
    """Выгрузка не собирается в справочник — названы все найденные причины.

    Битая версия ломает отбор строк, а следом рассыпается половина ссылок, и
    отдавать первую причину означало бы чинить файл по одному сообщению за
    прогон. В текст входят первые несколько причин, и порядок их нарочный:
    первой идёт версия, потому что без неё все прочие причины ложные.
    """

    _error_in_message = 6

    def __init__(self, errors: list[str]) -> None:
        self.errors = list(errors)
        rest = len(self.errors) - self._error_in_message
        super().__init__(
            f"критериальная выгрузка не собрана: "
            f"{'; '.join(self.errors[:self._error_in_message])}"
            + (f"; и ещё {rest}" if rest > 0 else "")
        )


def listing(values: list[str], limit: int = 5) -> str:
    """Перечень в сообщение: первые имена, остальное — числом."""
    head = ", ".join(values[:limit])
    rest = len(values) - limit
    return f"{head} и ещё {rest}" if rest > 0 else head
