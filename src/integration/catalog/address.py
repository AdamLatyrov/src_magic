"""Адрес дефекта: ключ проверки и код через двоеточие.

Формула принадлежит справочнику, и она одна на обе стороны: сборка обязана
писать адрес тем же способом, каким его разбирают, иначе найденный дефект
оказывается чужой проверкой. Разойтись им есть где — код различается только
внутри своей проверки (`CL-11` встречается у нескольких), поэтому голого кода
не хватает, чтобы понять, о чём находка, а лишний или пропущенный разделитель
сдвигает границу между ключом и кодом.

Отсюда и порядок: здесь и сборка адреса, и его разбор; кто бы к адресу ни
обращался, обе половины контракта берутся из одного места.
"""


def ref_of(check_key: str, code: str) -> str:
    """Адрес дефекта своей проверки."""
    return f"{check_key}:{code}"


def parts_of(raw: object) -> tuple[str, str]:
    """Адрес на «проверку» и «код»; голая метка — без проверки.

    Разделитель один — первое двоеточие: ключ проверки сам по себе двоеточия
    не содержит, и адрес с двумя значил бы, что разметка прислала что-то
    чужое, а не то, что код надо искать в конце строки.
    """
    text = str(raw or "")
    check, sep, code = text.partition(":")
    if not sep:
        return "", text.strip()
    return check.strip(), code.strip()


def check_key_of(raw: object) -> str:
    """Ключ проверки из адреса; пустая строка, если адреса нет.

    Адрес обязан содержать ровно одно двоеточие, и при правильном адресе это
    чтение совпадает с `parts_of`; читать с конца оставлено нарочно — так
    привязку находки к блоку читал балл, и сдвиг границы у мусорного ответа
    разметки переключил бы штраф на другой блок.
    """
    check, sep, _ = str(raw or "").rpartition(":")
    return check if sep else ""
